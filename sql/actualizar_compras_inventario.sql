-- Se ejecuta DESPUÉS de instalar_base_de_datos.sql (que crea los esquemas etl, stg, dw y mart),
-- conectado a la base gas_station_db con el usuario gas_station_db:
--   * con el ETL:   npm run instalar-bd   (ejecuta los dos scripts, en orden)
--   * con pgAdmin:  Query Tool sobre gas_station_db, abrir este archivo y ejecutar (F5)
--   * con psql:     psql -h 72.62.80.172 -p 5432 -U gas_station_db -d gas_station_db -v ON_ERROR_STOP=1 -f sql/actualizar_compras_inventario.sql
--
-- Se puede ejecutar las veces que haga falta: no borra datos ni duplica nada. No cambia
-- ninguna tabla, función ni vista de la versión 1.0.0 (tickets): solo agrega.
--
-- Qué agrega
--   stg.compra              las líneas del reporte de compras tal como vienen, ya tipadas
--   dw.dim_proveedor        proveedores (PUMA ENERGY...)
--   dw.fact_compra          una fila por factura de compra y producto
--   dw.toma_fisica          mediciones de los tanques que el usuario registra en el panel
--   dw.cargar_compras()     paso de staging a la estrella, idempotente como dw.cargar_tickets()
--   mart.existencia_en()    existencia de un producto en cualquier momento, desde la toma física más cercana
--   mart.v_compra, mart.v_toma_fisica_diferencia   vistas para consultar y para Power BI
-- =====================================================================

