-- ---------------------------------------------------------------------
-- stg: un renglón por línea del reporte de compras
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS stg.compra (
    carga_id          bigint  NOT NULL REFERENCES etl.carga ON DELETE CASCADE,
    fila_excel        int     NOT NULL,
    seccion           text,               -- encabezado de grupo del reporte (DIESEL, REGULAR, SUPER, lubricantes)
    estacion          text    NOT NULL,   -- el reporte no la trae: la opción del panel o ETL_ESTACION_POR_DEFECTO
    turno             int,                -- turno de BISS en que se registró la compra
    serie             text    NOT NULL,
    numero            text    NOT NULL,
    fecha_hora        timestamp NOT NULL, -- hora local en que entra el producto al inventario
    proveedor_nit     text,
    proveedor_nombre  text,               -- columna "Cliente" del reporte
    producto          text    NOT NULL,
    cantidad          numeric(14,5) NOT NULL, -- galones en combustibles, unidades en lubricantes
    precio            numeric(14,6),
    total             numeric(14,2) NOT NULL,
    fob_total         numeric(18,6),
    fob_unitario      numeric(18,9),
    cif_total         numeric(18,6),
    cif_unitario      numeric(18,9),
    anulada           boolean NOT NULL DEFAULT false,
    combustible       text,
    f1                numeric(18,6),
    f2                numeric(18,6),
    f3                numeric(18,6),
    PRIMARY KEY (carga_id, fila_excel)
);

-- ---------------------------------------------------------------------
-- dw: proveedores, hechos de compra y tomas físicas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS dw.dim_proveedor (
    proveedor_key  int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit            text NOT NULL UNIQUE,   -- sin guiones ni espacios
    nombre         text NOT NULL
);
INSERT INTO dw.dim_proveedor (proveedor_key, nit, nombre) VALUES (-1, 'N/D', 'No definido')
ON CONFLICT DO NOTHING;

-- Grano: una línea de factura de compra (una factura de PUMA trae Diesel, Regular y Super)
CREATE TABLE IF NOT EXISTS dw.fact_compra (
    estacion_key     int      NOT NULL REFERENCES dw.dim_estacion,
    producto_key     int      NOT NULL REFERENCES dw.dim_producto,
    proveedor_key    int      NOT NULL REFERENCES dw.dim_proveedor,
    fecha_key        int      NOT NULL REFERENCES dw.dim_fecha,
    hora_key         smallint NOT NULL REFERENCES dw.dim_hora,
    turno            int,
    factura_serie    text     NOT NULL,
    factura_numero   text     NOT NULL,
    fecha_hora       timestamp NOT NULL,
    cantidad         numeric(14,5) NOT NULL,
    precio_unitario  numeric(14,6),
    monto_total      numeric(14,2) NOT NULL,   -- lo facturado
    fob_total        numeric(18,6),            -- costo
    fob_unitario     numeric(18,9),
    cif_total        numeric(18,6),
    cif_unitario     numeric(18,9),
    anulada          boolean  NOT NULL DEFAULT false,  -- no suma al inventario
    f1               numeric(18,6),
    f2               numeric(18,6),
    f3               numeric(18,6),
    carga_id_alta    bigint   NOT NULL REFERENCES etl.carga,
    carga_id_ultima  bigint   NOT NULL REFERENCES etl.carga,
    carga_id_cambio  bigint   NOT NULL REFERENCES etl.carga,
    hash_fila        text     NOT NULL,
    PRIMARY KEY (estacion_key, factura_serie, factura_numero, producto_key)
);
CREATE INDEX IF NOT EXISTS ix_compra_producto_fecha ON dw.fact_compra (estacion_key, producto_key, fecha_hora);

-- Medición de un tanque (o de todos los de un producto) a una hora. La registra el usuario en el panel;
-- una toma equivocada no se borra: se anula y queda quién y cuándo
CREATE TABLE IF NOT EXISTS dw.toma_fisica (
    toma_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    estacion_key   int       NOT NULL REFERENCES dw.dim_estacion,
    producto_key   int       NOT NULL REFERENCES dw.dim_producto,
    fecha_hora     timestamp NOT NULL,          -- hora local de la medición
    galones        numeric(14,3) NOT NULL CHECK (galones >= 0),
    observaciones  text,
    usuario        text,
    registrada_en  timestamptz NOT NULL DEFAULT now(),
    anulada        boolean   NOT NULL DEFAULT false,
    anulada_en     timestamptz,
    anulada_por    text
);
-- Una sola toma vigente por estación, producto y hora
CREATE UNIQUE INDEX IF NOT EXISTS ux_toma_vigente ON dw.toma_fisica (estacion_key, producto_key, fecha_hora) WHERE NOT anulada;

-- Índice para sumar las ventas de un producto en un rango de horas (existencias)
CREATE INDEX IF NOT EXISTS ix_despacho_estacion_producto_hora ON dw.fact_despacho (estacion_key, producto_key, fecha_hora);

-- Huella de los valores de una línea de compra: la usan la carga y la vista previa del panel
-- para saber si una compra ya cargada cambió
CREATE OR REPLACE FUNCTION dw.huella_compra(
    p_turno int, p_fecha_hora timestamp, p_nit text, p_cantidad numeric, p_precio numeric, p_total numeric,
    p_fob_total numeric, p_cif_total numeric, p_anulada boolean)
RETURNS text LANGUAGE sql IMMUTABLE AS $$
    SELECT md5(concat_ws('|', p_turno, p_fecha_hora,
                         upper(nullif(regexp_replace(coalesce(p_nit, ''), '[\s-]', '', 'g'), '')),
                         round(p_cantidad, 5), round(p_precio, 6), round(p_total, 2),
                         round(p_fob_total, 4), round(p_cif_total, 4), p_anulada))
$$;

-- =====================================================================
-- Paso de staging a la estrella para una carga del "Reporte de compras".
-- El ETL lee el Excel, valida, cuadra contra los subtotales, copia las líneas a
-- stg.compra y llama, en la misma transacción:
--     SELECT * FROM dw.cargar_compras(carga_id);
-- Es idempotente: cargar otra vez el mismo período actualiza solo las líneas que
-- cambiaron (el último archivo manda) y deja constancia en etl.cambio.
-- =====================================================================
CREATE OR REPLACE FUNCTION dw.cargar_compras(p_carga_id bigint)
RETURNS TABLE (insertadas int, actualizadas int, sin_cambio int, no_vinieron int)
LANGUAGE plpgsql AS $$
DECLARE
    v_ins   int := 0;
    v_upd   int := 0;
    v_igual int := 0;
    v_falt  int := 0;
BEGIN
    -- Dos cargas de compras a la vez se ponen en fila
    PERFORM pg_advisory_xact_lock(hashtext('dw.cargar_compras'));

    -- 1) Normalizar lo que vino en staging -----------------------------------------
    DROP TABLE IF EXISTS t_cstg;
    CREATE TEMP TABLE t_cstg ON COMMIT DROP AS
    SELECT s.*,
           CASE WHEN strpos(s.estacion, ' - ') > 0 THEN trim(split_part(s.estacion, ' - ', 1))
                ELSE trim(s.estacion) END                                   AS est_codigo,
           CASE WHEN strpos(s.estacion, ' - ') > 0 THEN trim(substr(s.estacion, strpos(s.estacion, ' - ') + 3))
                ELSE trim(s.estacion) END                                   AS est_nombre,
           trim(s.serie)                                                    AS f_serie,
           trim(s.numero)                                                   AS f_numero,
           upper(trim(s.producto))                                          AS prod,
           coalesce(upper(nullif(regexp_replace(coalesce(s.proveedor_nit, ''), '[\s-]', '', 'g'), '')), 'N/D') AS prov_nit,
           coalesce(nullif(regexp_replace(trim(coalesce(s.proveedor_nombre, '')), '\s+', ' ', 'g'), ''), 'No definido') AS prov_nombre,
           to_char(s.fecha_hora, 'YYYYMMDD')::int                           AS fecha_key,
           (extract(hour FROM s.fecha_hora) * 60 + extract(minute FROM s.fecha_hora))::smallint AS hora_key,
           dw.huella_compra(s.turno, s.fecha_hora, s.proveedor_nit, s.cantidad, s.precio, s.total,
                            s.fob_total, s.cif_total, s.anulada)            AS hash_fila
    FROM stg.compra s
    WHERE s.carga_id = p_carga_id;

    IF NOT EXISTS (SELECT 1 FROM t_cstg) THEN
        RAISE EXCEPTION 'La carga % no tiene compras en staging', p_carga_id;
    END IF;
    IF EXISTS (SELECT 1 FROM t_cstg GROUP BY est_codigo, f_serie, f_numero, prod HAVING count(*) > 1) THEN
        RAISE EXCEPTION 'La carga % trae compras repetidas (misma factura y producto)', p_carga_id;
    END IF;

    PERFORM dw.llenar_calendario(min(fecha_hora)::date, max(fecha_hora)::date) FROM t_cstg;

    -- 2) Dimensiones -----------------------------------------------------------------
    INSERT INTO dw.dim_estacion AS d (codigo, nombre)
    SELECT DISTINCT ON (est_codigo) est_codigo, est_nombre FROM t_cstg ORDER BY est_codigo
    ON CONFLICT (codigo) DO UPDATE SET nombre = EXCLUDED.nombre
    WHERE d.nombre IS DISTINCT FROM EXCLUDED.nombre AND EXCLUDED.nombre <> EXCLUDED.codigo;

    -- Misma clasificación que dw.cargar_tickets: solo Diesel, Regular y Super son combustible
    INSERT INTO dw.dim_producto (nombre_origen, nombre, familia, tipo, unidad)
    SELECT DISTINCT prod, prod,
           CASE WHEN prod IN ('DIESEL', 'REGULAR', 'SUPER') THEN 'COMBUSTIBLE' ELSE 'N/D' END,
           CASE prod WHEN 'DIESEL' THEN 'DIESEL' WHEN 'REGULAR' THEN 'GASOLINA' WHEN 'SUPER' THEN 'GASOLINA' END,
           CASE WHEN prod IN ('DIESEL', 'REGULAR', 'SUPER') THEN 'GALON' END
    FROM t_cstg
    ON CONFLICT (nombre_origen) DO NOTHING;

    INSERT INTO dw.dim_proveedor AS d (nit, nombre)
    SELECT prov_nit, mode() WITHIN GROUP (ORDER BY prov_nombre)
    FROM t_cstg WHERE prov_nit <> 'N/D'
    GROUP BY prov_nit
    ON CONFLICT (nit) DO UPDATE SET nombre = EXCLUDED.nombre
    WHERE d.nombre IS DISTINCT FROM EXCLUDED.nombre;

    -- 3) Hechos: resolver llaves --------------------------------------------------------
    DROP TABLE IF EXISTS t_checho;
    CREATE TEMP TABLE t_checho ON COMMIT DROP AS
    SELECT e.estacion_key,
           p.producto_key,
           coalesce(pr.proveedor_key, -1) AS proveedor_key,
           s.fecha_key,
           s.hora_key,
           s.turno,
           s.f_serie                      AS factura_serie,
           s.f_numero                     AS factura_numero,
           s.fecha_hora,
           s.cantidad,
           s.precio                       AS precio_unitario,
           s.total                        AS monto_total,
           s.fob_total, s.fob_unitario, s.cif_total, s.cif_unitario,
           s.anulada, s.f1, s.f2, s.f3,
           s.hash_fila,
           s.prov_nit,
           f0.hash_fila                   AS hash_anterior
    FROM t_cstg s
    JOIN dw.dim_estacion e        ON e.codigo = s.est_codigo
    JOIN dw.dim_producto p        ON p.nombre_origen = s.prod
    LEFT JOIN dw.dim_proveedor pr ON pr.nit = s.prov_nit
    LEFT JOIN dw.fact_compra f0   ON (f0.estacion_key, f0.factura_serie, f0.factura_numero, f0.producto_key)
                                   = (e.estacion_key, s.f_serie, s.f_numero, p.producto_key);

    SELECT count(*) FILTER (WHERE hash_anterior IS NULL),
           count(*) FILTER (WHERE hash_anterior IS NOT NULL AND hash_anterior <> hash_fila),
           count(*) FILTER (WHERE hash_anterior = hash_fila)
    INTO v_ins, v_upd, v_igual
    FROM t_checho;

    -- 4) Bitácora de lo que cambió en compras ya cargadas ------------------------------
    INSERT INTO etl.cambio (carga_id, entidad, llave, campo, valor_anterior, valor_nuevo)
    SELECT p_carga_id, 'COMPRA', e.codigo || '-' || h.factura_serie || '-' || h.factura_numero || '-' || p.nombre_origen,
           x.campo, x.antes, x.despues
    FROM t_checho h
    JOIN dw.fact_compra f     ON (f.estacion_key, f.factura_serie, f.factura_numero, f.producto_key)
                               = (h.estacion_key, h.factura_serie, h.factura_numero, h.producto_key)
    JOIN dw.dim_estacion e    ON e.estacion_key = h.estacion_key
    JOIN dw.dim_producto p    ON p.producto_key = h.producto_key
    JOIN dw.dim_proveedor pr1 ON pr1.proveedor_key = f.proveedor_key
    CROSS JOIN LATERAL (VALUES
        ('turno',      f.turno::text,             h.turno::text),
        ('fecha_hora', f.fecha_hora::text,        h.fecha_hora::text),
        ('proveedor',  pr1.nit,                   h.prov_nit),
        ('cantidad',   f.cantidad::text,          h.cantidad::text),
        ('precio',     f.precio_unitario::text,   h.precio_unitario::text),
        ('total',      f.monto_total::text,       h.monto_total::text),
        ('fob_total',  round(f.fob_total, 4)::text, round(h.fob_total, 4)::text),
        ('cif_total',  round(f.cif_total, 4)::text, round(h.cif_total, 4)::text),
        ('anulada',    f.anulada::text,           h.anulada::text)
    ) AS x(campo, antes, despues)
    WHERE f.hash_fila <> h.hash_fila
      AND x.antes IS DISTINCT FROM x.despues;

    -- 5) Insertar nuevas y refrescar las existentes (el último archivo manda) -----------
    INSERT INTO dw.fact_compra AS f (
        estacion_key, producto_key, proveedor_key, fecha_key, hora_key, turno, factura_serie, factura_numero,
        fecha_hora, cantidad, precio_unitario, monto_total, fob_total, fob_unitario, cif_total, cif_unitario,
        anulada, f1, f2, f3, carga_id_alta, carga_id_ultima, carga_id_cambio, hash_fila)
    SELECT estacion_key, producto_key, proveedor_key, fecha_key, hora_key, turno, factura_serie, factura_numero,
           fecha_hora, cantidad, precio_unitario, monto_total, fob_total, fob_unitario, cif_total, cif_unitario,
           anulada, f1, f2, f3, p_carga_id, p_carga_id, p_carga_id, hash_fila
    FROM t_checho
    ON CONFLICT (estacion_key, factura_serie, factura_numero, producto_key) DO UPDATE
    SET proveedor_key = EXCLUDED.proveedor_key,
        fecha_key = EXCLUDED.fecha_key,
        hora_key = EXCLUDED.hora_key,
        turno = EXCLUDED.turno,
        fecha_hora = EXCLUDED.fecha_hora,
        cantidad = EXCLUDED.cantidad,
        precio_unitario = EXCLUDED.precio_unitario,
        monto_total = EXCLUDED.monto_total,
        fob_total = EXCLUDED.fob_total,
        fob_unitario = EXCLUDED.fob_unitario,
        cif_total = EXCLUDED.cif_total,
        cif_unitario = EXCLUDED.cif_unitario,
        anulada = EXCLUDED.anulada,
        f1 = EXCLUDED.f1,
        f2 = EXCLUDED.f2,
        f3 = EXCLUDED.f3,
        carga_id_ultima = EXCLUDED.carga_id_ultima,
        carga_id_cambio = CASE WHEN f.hash_fila <> EXCLUDED.hash_fila THEN EXCLUDED.carga_id_cambio
                               ELSE f.carga_id_cambio END,
        hash_fila = EXCLUDED.hash_fila;

    -- 6) Compras ya cargadas que no vinieron, dentro del rango de fechas que trae el archivo
    --    (una factura anulada y borrada en BISS, o un archivo filtrado por producto). No se borran
    INSERT INTO etl.incidencia (carga_id, severidad, regla, columna, valor, mensaje)
    SELECT p_carga_id, 'ADVERTENCIA', 'COMPRA_NO_VINO', 'factura',
           f.factura_serie || '-' || f.factura_numero,
           'La compra ' || f.factura_serie || '-' || f.factura_numero || ' de ' || p.nombre || ' (' ||
           to_char(f.fecha_hora, 'DD/MM/YYYY HH24:MI') || ') estaba cargada y no viene en este archivo; sigue contando en el inventario'
    FROM (SELECT estacion_key, min(fecha_hora) AS desde, max(fecha_hora) AS hasta FROM t_checho GROUP BY estacion_key) r
    JOIN dw.fact_compra f  ON f.estacion_key = r.estacion_key AND f.fecha_hora BETWEEN r.desde AND r.hasta
    JOIN dw.dim_producto p ON p.producto_key = f.producto_key
    WHERE NOT EXISTS (SELECT 1 FROM t_checho h
                      WHERE (h.estacion_key, h.factura_serie, h.factura_numero, h.producto_key)
                          = (f.estacion_key, f.factura_serie, f.factura_numero, f.producto_key));
    GET DIAGNOSTICS v_falt = ROW_COUNT;

    -- 7) Cerrar la carga -----------------------------------------------------------------
    UPDATE etl.carga c
    SET estado = 'CARGADO',
        terminado_en = clock_timestamp(),
        estacion_codigo = x.est,
        turno_min = x.tmin, turno_max = x.tmax,
        fecha_min = x.fmin, fecha_max = x.fmax,
        filas_detalle = x.n,
        insertadas = v_ins, actualizadas = v_upd, sin_cambio = v_igual
    FROM (SELECT string_agg(DISTINCT est_codigo, ',') AS est, min(turno) AS tmin, max(turno) AS tmax,
                 min(fecha_hora) AS fmin, max(fecha_hora) AS fmax, count(*) AS n
          FROM t_cstg) x
    WHERE c.carga_id = p_carga_id;

    RETURN QUERY SELECT v_ins, v_upd, v_igual, v_falt;
END $$;

-- =====================================================================
-- Existencias. El inventario de un producto en un momento M se calcula desde la toma física
-- más cercana: la última hecha a esa hora o antes (si no hay, la primera después).
--   toma a las T <= M:  existencia(M) = toma + compras - ventas con fecha_hora en [T, M)
--   toma a las T >  M:  existencia(M) = toma - compras + ventas con fecha_hora en [M, T)
-- Una venta o compra registrada justo a la hora de la toma cuenta como posterior a ella.
-- Las compras anuladas no suman. Sin ninguna toma del producto no se puede saber: devuelve 0 filas.
-- =====================================================================
CREATE OR REPLACE FUNCTION mart.movimiento_neto(p_estacion_key int, p_producto_key int, p_desde timestamp, p_hasta timestamp)
RETURNS numeric LANGUAGE sql STABLE AS $$
    SELECT coalesce((SELECT sum(c.cantidad) FROM dw.fact_compra c
                      WHERE c.estacion_key = p_estacion_key AND c.producto_key = p_producto_key AND NOT c.anulada
                        AND c.fecha_hora >= p_desde AND c.fecha_hora < p_hasta), 0)
         - coalesce((SELECT sum(f.cantidad_gal) FROM dw.fact_despacho f
                      WHERE f.estacion_key = p_estacion_key AND f.producto_key = p_producto_key
                        AND f.fecha_key BETWEEN to_char(p_desde, 'YYYYMMDD')::int AND to_char(p_hasta, 'YYYYMMDD')::int
                        AND f.fecha_hora >= p_desde AND f.fecha_hora < p_hasta), 0)
$$;

CREATE OR REPLACE FUNCTION mart.existencia_en(p_estacion_key int, p_producto_key int, p_momento timestamp)
RETURNS TABLE (galones numeric, toma_id bigint, toma_fecha_hora timestamp, toma_galones numeric)
LANGUAGE sql STABLE AS $$
    WITH ancla AS (
        SELECT t.toma_id, t.fecha_hora, t.galones
          FROM dw.toma_fisica t
         WHERE t.estacion_key = p_estacion_key AND t.producto_key = p_producto_key AND NOT t.anulada
         ORDER BY t.fecha_hora > p_momento,   -- primero las de antes (o de esa misma hora)
                  abs(extract(epoch FROM t.fecha_hora - p_momento)),
                  t.toma_id DESC
         LIMIT 1
    )
    SELECT a.galones + CASE WHEN a.fecha_hora <= p_momento
                            THEN mart.movimiento_neto(p_estacion_key, p_producto_key, a.fecha_hora, p_momento)
                            ELSE -mart.movimiento_neto(p_estacion_key, p_producto_key, p_momento, a.fecha_hora) END,
           a.toma_id, a.fecha_hora, a.galones
      FROM ancla a
$$;

-- Vista ancha de compras (fuente para Power BI y consultas)
CREATE OR REPLACE VIEW mart.v_compra AS
SELECT e.codigo   AS estacion,
       c.factura_serie, c.factura_numero, c.turno,
       c.fecha_hora, d.fecha, d.anio, d.mes, d.anio_mes, d.semana_iso, d.nombre_dia,
       p.nombre   AS producto,
       p.familia  AS familia_producto,
       pr.nit     AS proveedor_nit,
       pr.nombre  AS proveedor,
       c.cantidad, c.precio_unitario, c.monto_total, c.fob_total, c.fob_unitario, c.cif_total, c.cif_unitario,
       c.anulada
FROM dw.fact_compra c
JOIN dw.dim_estacion e  ON e.estacion_key = c.estacion_key
JOIN dw.dim_producto p  ON p.producto_key = c.producto_key
JOIN dw.dim_proveedor pr ON pr.proveedor_key = c.proveedor_key
JOIN dw.dim_fecha d     ON d.fecha_key = c.fecha_key;

-- Cada toma física contra lo que debía haber según la toma anterior del mismo producto, más
-- compras y menos ventas entre las dos: la diferencia es el faltante (negativo) o sobrante (positivo)
CREATE OR REPLACE VIEW mart.v_toma_fisica_diferencia AS
SELECT e.codigo AS estacion,
       p.nombre AS producto,
       t.toma_id,
       t.fecha_hora,
       t.galones,
       a.fecha_hora AS toma_anterior_en,
       a.galones    AS toma_anterior_galones,
       a.galones + mart.movimiento_neto(t.estacion_key, t.producto_key, a.fecha_hora, t.fecha_hora) AS galones_teoricos,
       t.galones - (a.galones + mart.movimiento_neto(t.estacion_key, t.producto_key, a.fecha_hora, t.fecha_hora)) AS diferencia,
       t.usuario,
       t.observaciones
FROM dw.toma_fisica t
JOIN dw.dim_estacion e ON e.estacion_key = t.estacion_key
JOIN dw.dim_producto p ON p.producto_key = t.producto_key
LEFT JOIN LATERAL (
    SELECT x.fecha_hora, x.galones FROM dw.toma_fisica x
     WHERE x.estacion_key = t.estacion_key AND x.producto_key = t.producto_key AND NOT x.anulada
       AND x.fecha_hora < t.fecha_hora
     ORDER BY x.fecha_hora DESC, x.toma_id DESC
     LIMIT 1
) a ON true
WHERE NOT t.anulada;

